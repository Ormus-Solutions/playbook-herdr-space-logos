def snapshot(folder: Path) -> dict[str, str]:
    return {str(p.relative_to(folder)): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in sorted(folder.rglob("*")) if p.is_file()}


def demo() -> int:
    """Install into a temporary copy of the synthetic Herdr home, then undo."""
    config = load_config(EXAMPLES / "spaces.json")
    out = [describe(config)]
    with tempfile.TemporaryDirectory() as tmp:
        home = Path(tmp) / "herdr-home"
        shutil.copytree(EXAMPLES / "herdr-home", home)
        before = snapshot(home)
        out.append("Install into a copy of examples/herdr-home (a synthetic Herdr home):")
        out += install(config, home, layout="logos", keys=True)
        out += ["", "Undo:"] + undo(home)
        back = "yes" if snapshot(home) == before else "NO"
        out.append(f"The demo home is back as it was: {back}")
    sys.stdout.write("\n".join(out) + "\n")
    return 0 if back == "yes" else 1


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Give each Herdr space a logo in the sidebar and the picker.")
    parser.add_argument("--demo", action="store_true", help="install and undo on the synthetic data in examples/")
    sub = parser.add_subparsers(dest="command")
    for name, text in (("check", "check the config and that the patch fits your Herdr; writes nothing"),
                       ("install", "write the logo mods into the Herdr home"),
                       ("undo", "remove everything install wrote, restore the files it changed"),
                       ("preview", "draw the sidebar tiles of your config as an SVG")):
        p = sub.add_parser(name, help=text)
        if name != "undo":
            p.add_argument("--config", help=f"the spaces.json (default: $SPACE_LOGOS_CONFIG or {DEFAULT_CONFIG})")
        if name != "preview":
            p.add_argument("--home", help=f"the Herdr app home (default: $HERDR_APP_HOME or {DEFAULT_HOME})")
        if name == "install":
            p.add_argument("--layout", help="also point this layout of yours (a clone) at the new mods")
            p.add_argument("--keys", action="store_true", help="also point the keys that open the picker at the new one")
        if name == "preview":
            p.add_argument("--svg", required=True, type=Path, help="the SVG file to write")
    args = parser.parse_args(argv)

    if args.demo:
        return demo()
    if args.command is None:
        parser.error("give a command (check, install, undo, preview), or --demo")
    if args.command == "undo":
        home = home_path(args.home)
        print(f"Undo in the Herdr home {home}:")
        print("\n".join(undo(home)))
        return 0
    config = load_config(config_path(args.config))
    if args.command == "preview":
        args.svg.write_text(preview_svg(config), encoding="utf-8")
        print(f"wrote {args.svg}")
        return 0
    home = home_path(args.home)
    sys.stdout.write(describe(config) + "\n")
    if args.command == "check":
        for name, (_code, _meta, edits) in plan(config, home).items():
            print(f"mods/{name}: the patch fits ({edits} edits)")
        print("check: ok (nothing was written)")
        return 0
    print(f"Install into the Herdr home {home}:")
    print("\n".join(install(config, home, args.layout, args.keys)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
