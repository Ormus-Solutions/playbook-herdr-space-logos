#!/usr/bin/env python3
"""A logo for every Herdr space: the reference implementation.

Herdr's desktop app draws each space in the sidebar and in the Go to picker as
a small colored tile with the first letter of its name. This tool makes copies
of Herdr's own `spaces` and `picker` mods that draw a logo instead, where your
spaces.json gives one, and a letter tile with your letter and color where it
does not.

The pattern is an anchored patch. Herdr's shipped mods are read-only (Herdr
rewrites them on every start), so the tool reads them, makes a few exact edits
and writes the result as new mods next to them. Each edit looks for one exact
piece of Herdr's code, its anchor. When a Herdr update moves that code, the
anchor is gone and the tool stops with a clear message, instead of writing a
broken mod. Your last good copy keeps working until you update the anchor.

Usage:
    python3 src/space_logos.py --demo
    python3 src/space_logos.py check   [--config FILE] [--home DIR]
    python3 src/space_logos.py install [--config FILE] [--home DIR] [--layout NAME] [--keys]
    python3 src/space_logos.py undo    [--home DIR]
    python3 src/space_logos.py preview [--config FILE] --svg FILE

Settings: the config file is $SPACE_LOGOS_CONFIG, else
~/.config/herdr-space-logos/spaces.json. The Herdr home is --home, else
$HERDR_APP_HOME, else ~/.config/herdr-app.
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import json
import os
import re
import shutil
import sys
import tempfile
import xml.etree.ElementTree as ET
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EXAMPLES = ROOT / "examples"
DEFAULT_CONFIG = "~/.config/herdr-space-logos/spaces.json"
DEFAULT_HOME = "~/.config/herdr-app"

MARKER = ".made-by-space-logos"  # in every mod folder this tool writes
BACKUP = ".bak-space-logos"      # suffix of the one backup kept per file it changes
SHIPPED_LAYOUTS = {"main", "terminals", "win98"}  # Herdr replaces these on every start

ENTRY_KEYS = {"logo", "bg", "pad", "letter", "color", "text"}
TOP_KEYS = {"spaces", "logos", "separator", "spaces_mod", "picker_mod"}
HEX = re.compile(r"^#[0-9a-fA-F]{6}$")
LOGO_FILE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*\.(svg|png)$")
MOD_NAME = re.compile(r"^[a-z0-9][a-z0-9-]*$")
LAYOUT_NAME = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*$")  # no slash, so it stays in layouts/

# The anchors: the exact code in Herdr's mods (herdr-app 0.1.15) that draws a
# space's letter tile, and what replaces it. Each must appear exactly once.
TILE_EDITS = {
    "spaces": (
        'el.child(h_flex().size(18).flex_none().rounded(5).bg(fill).items_center()'
        '.justify_center().text_size(10.5).font_bold().text_color("#ffffff")'
        '.child([...w.name][0]?.toUpperCase() ?? "?"))',
        "el.child(spaceLogoTile(w, fill))",
    ),
    "picker": (
        '.child(h_flex().size(18).rounded(5).bg(spaceColor(t, r.w)).items_center()'
        '.justify_center().text_size(10.5).font_bold().text_color("#ffffff")'
        '.child([...r.w.name][0]?.toUpperCase() ?? "?"))',
        ".child(spaceLogoTile(r.w, spaceColor(t, r.w)))",
    ),
}
# The gpui-kit import, on one line or several: `[^}]*` runs across lines.
GPUI_IMPORT = re.compile(r'^import \{([^}]*)\} from "gpui-kit";$', re.M)
# Any import statement, on one line or several, up to its semicolon; not a
# call such as import("x") or import.meta.
ANY_IMPORT = re.compile(r"^import\b(?!\s*[(.])[^;]*;", re.M)
BLOCK_START = "// --- space logos: generated by playbook-herdr-space-logos from spaces.json"
PURE_END = "// --- end of the part the tests run in node ---"
BLOCK_END = "// --- end of space logos ---"

SVG_NS = "http://www.w3.org/2000/svg"
ET.register_namespace("", SVG_NS)  # write <svg>, not <ns0:svg>

# Herdr's own space colors, used by the SVG preview for a letter tile with no color.
HERDR_COLORS = ["#22a99a", "#e3814f", "#5b8def", "#8b7cf6", "#3fae6a", "#d9649a"]


class Stop(SystemExit):
    """A clear message for the person, and exit code 1."""

    def __init__(self, message: str) -> None:
        super().__init__(f"space-logos: {message}")


@dataclass
class Config:
    path: Path
    spaces: dict[str, dict]
    logos: Path
    separator: str
    spaces_mod: str
    picker_mod: str


# ---- the config --------------------------------------------------------------

def config_path(given: str | None) -> Path:
    return Path(given or os.environ.get("SPACE_LOGOS_CONFIG") or DEFAULT_CONFIG).expanduser()


def home_path(given: str | None) -> Path:
    return Path(given or os.environ.get("HERDR_APP_HOME") or DEFAULT_HOME).expanduser()


def logo_is_valid(file: Path) -> bool:
    """A PNG starts with its 8-byte signature; an SVG is XML with an <svg> root."""
    if file.suffix.lower() == ".png":
        return file.read_bytes()[:8] == b"\x89PNG\r\n\x1a\n"
    try:
        return ET.fromstring(file.read_text(encoding="utf-8")).tag in ("svg", f"{{{SVG_NS}}}svg")
    except (ET.ParseError, UnicodeDecodeError):
        return False


def check_entry(name: str, entry: object, logos: Path) -> dict:
    """One space's entry: a logo (with an optional bg and pad), or a letter tile."""
    where = f"spaces.json: {name!r}"
    if not isinstance(entry, dict):
        raise Stop(f"{where} must be an object, like {{\"logo\": \"web.svg\"}}")
    unknown = set(entry) - ENTRY_KEYS
    if unknown:
        raise Stop(f"{where}: unknown key {sorted(unknown)}; use {sorted(ENTRY_KEYS)}")
    for key in ("bg", "color", "text"):
        if key in entry and not (isinstance(entry[key], str) and HEX.match(entry[key])):
            raise Stop(f"{where}: {key} must be a color like \"#3a7bd5\"")
    if "logo" in entry:
        logo = entry["logo"]
        if not isinstance(logo, str) or not LOGO_FILE.match(logo):
            raise Stop(f"{where}: logo must be a file name like web.svg or web.png "
                       "(letters, digits, dot, dash, underscore)")
        if not (logos / logo).is_file():
            raise Stop(f"{where}: the logo {logo} is not in {logos.name}/")
        if not logo_is_valid(logos / logo):
            raise Stop(f"{where}: {logo} is not a valid {Path(logo).suffix[1:].upper()} file")
        if {"letter", "color", "text"} & set(entry):
            raise Stop(f"{where}: give a logo or a letter tile (letter, color, text), not both")
    elif {"bg", "pad"} & set(entry):
        raise Stop(f"{where}: bg and pad go with a logo")
    if "pad" in entry:
        pad = entry["pad"]
        if isinstance(pad, bool) or not isinstance(pad, int) or not 0 <= pad <= 6:
            raise Stop(f"{where}: pad must be a whole number of pixels from 0 to 6")
    if "letter" in entry:
        letter = entry["letter"]
        if not isinstance(letter, str) or not 1 <= len(letter) <= 2 or letter != letter.strip():
            raise Stop(f"{where}: letter must be one or two characters, like \"D\" or \"QA\"")
    return dict(entry)


def load_config(path: Path) -> Config:
    if not path.is_file():
        raise Stop(f"no config at {path}: copy examples/spaces.json there and change it, "
                   "or pass --config")
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as err:
        raise Stop(f"{path.name} is not valid JSON: line {err.lineno}, column {err.colno}")
    if not isinstance(data, dict):
        raise Stop(f"{path.name} must hold an object with a \"spaces\" key")
    unknown = {k for k in data if not k.startswith("$")} - TOP_KEYS
    if unknown:
        raise Stop(f"{path.name}: unknown key {sorted(unknown)}; use {sorted(TOP_KEYS)}")
    spaces = data.get("spaces")
    if not isinstance(spaces, dict) or not spaces:
        raise Stop(f"{path.name}: \"spaces\" must map at least one space name to its tile")
    logos = path.parent / str(data.get("logos", "logos"))
    separator = data.get("separator", "")
    if not isinstance(separator, str):
        raise Stop(f"{path.name}: separator must be text, like \" · \"")
    mods = {}
    for key, default in (("spaces_mod", "logo-spaces"), ("picker_mod", "logo-picker")):
        value = data.get(key, default)
        if not isinstance(value, str) or not MOD_NAME.match(value) or value in ("spaces", "picker"):
            raise Stop(f"{path.name}: {key} must be a new mod name in lowercase letters, "
                       "digits and dashes, not Herdr's own")
        mods[key] = value
    if mods["spaces_mod"] == mods["picker_mod"]:
        raise Stop(f"{path.name}: spaces_mod and picker_mod need two different names")
    checked = {}
    for name, entry in spaces.items():
        if not name.strip():
            raise Stop(f"{path.name}: a space name is empty")
        checked[name] = check_entry(name, entry, logos)
    return Config(path, checked, logos, separator, mods["spaces_mod"], mods["picker_mod"])


# ---- the tile: one rule, in Python for the preview and in JavaScript for Herdr

def letter_for(name: str, separator: str) -> str:
    """The letter a space without its own shows. Without a separator this is
    Herdr's rule (the first letter of the name); with one, the first letter
    after it, so "acme · WEB" and "acme · API" show W and A, not A twice."""
    part = name.split(separator, 1)[1].strip() if separator and separator in name else name
    return ((part or name)[:1] or "?").upper()


def tile_table(config: Config) -> dict[str, dict]:
    """What the mods need per space, with each logo's path in the Herdr home."""
    table = {}
    for name, entry in config.spaces.items():
        row = dict(entry)
        if "logo" in row:
            row["logo"] = f"mods/{config.spaces_mod}/logos/{row['logo']}"
        table[name] = row
    return table


def tile_js(config: Config) -> str:
    table = json.dumps(tile_table(config), ensure_ascii=False, sort_keys=True)
    sep = json.dumps(config.separator, ensure_ascii=False)
    return f"""{BLOCK_START}; edit that file, not this block ---
const SPACE_LOGOS = {table};
const SPACE_LOGOS_SEPARATOR = {sep};
function spaceLogoLetter(name) {{
  const sep = SPACE_LOGOS_SEPARATOR;
  const part = sep && name.includes(sep) ? name.slice(name.indexOf(sep) + sep.length).trim() : name;
  return ([...(part || name)][0] ?? "?").toUpperCase();
}}
{PURE_END}
function spaceLogoTile(w, fill) {{
  const o = SPACE_LOGOS[w.name] ?? {{}};
  const tile = h_flex().size(18).flex_none().rounded(5).items_center().justify_center();
  if (o.logo) {{
    return tile.when(Boolean(o.bg), (el) => el.bg(o.bg)).child(image(o.logo).size(18 - 2 * (o.pad ?? 0)));
  }}
  const letter = o.letter ?? spaceLogoLetter(w.name);
  return tile.bg(o.color ?? fill).text_size([...letter].length > 1 ? 8.5 : 10.5).font_bold()
    .text_color(o.text ?? "#ffffff").child(letter);
}}
{BLOCK_END}
"""


# ---- the anchored patch --------------------------------------------------------

def patch(src: str, which: str, block: str) -> tuple[str, int]:
    """Herdr's `spaces` or `picker` main.js, with the logo tile. Returns the new
    code and the number of edits. Stops when an anchor is gone."""
    gone = (f"Herdr changed its {which} mod, so the patch no longer fits "
            f"(the anchor for {{what}} is gone or not unique). Your old copy keeps "
            "working. See PLAYBOOK.md, \"When Herdr changes its mods\".")
    if BLOCK_START in src:
        raise Stop(f"this {which} main.js is already patched; patch Herdr's shipped mod, not a copy")
    edits = 0
    imports = GPUI_IMPORT.findall(src)
    if len(imports) != 1:
        raise Stop(gone.format(what="the gpui-kit import"))
    # The name each import binds: `image`, or the alias after `as`.
    names = [re.split(r"\s+as\s+", n.strip())[-1] for n in imports[0].split(",") if n.strip()]
    if "image" not in names:
        def add_image(m: re.Match[str]) -> str:
            # Drop a trailing comma first ("svg,\n}" is valid JavaScript, "svg,, image" is not).
            inner = m.group(1).rstrip().rstrip(",")
            return f'import {{{inner}{", " if inner.strip() else " "}image }} from "gpui-kit";'
        src = GPUI_IMPORT.sub(add_image, src, 1)
        edits += 1
    # The gpui-kit import matched, so there is at least one import statement.
    last = list(ANY_IMPORT.finditer(src))[-1]
    src = src[:last.end()] + "\n" + block + src[last.end():]
    edits += 1
    old, new = TILE_EDITS[which]
    if src.count(old) != 1:
        raise Stop(gone.format(what="the space's letter tile"))
    return src.replace(old, new), edits + 1


# ---- writing into the Herdr home -------------------------------------------------

def write_text(path: Path, text: str) -> None:
    """Write through a hidden temp file and a rename. Herdr reloads a mod on every
    save, so it must never see a half-written file (it skips hidden files)."""
    tmp = path.with_name("." + path.name + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, path)


def own_folder(folder: Path, home: Path) -> None:
    """Stop unless the folder is new or one this tool made: never overwrite."""
    if folder.exists() and not (folder / MARKER).is_file():
        raise Stop(f"{folder.relative_to(home)} exists and this tool did not make it; "
                   "pick another name in spaces.json (spaces_mod, picker_mod)")


def base_mod(home: Path, which: str) -> tuple[str, dict]:
    folder = home / "mods" / which
    main_js, mod_json = folder / "main.js", folder / "mod.json"
    if not main_js.is_file() or not mod_json.is_file():
        raise Stop(f"no Herdr {which} mod at mods/{which} in {home}: is this the Herdr app "
                   "home? Start Herdr once, or pass --home (or set HERDR_APP_HOME)")
    return main_js.read_text(encoding="utf-8"), json.loads(mod_json.read_text(encoding="utf-8"))


def plan(config: Config, home: Path) -> dict[str, tuple[str, dict, int]]:
    """Patch both mods in memory: what install would write. Writes nothing."""
    block = tile_js(config)
    out = {}
    for which, name in (("spaces", config.spaces_mod), ("picker", config.picker_mod)):
        src, meta = base_mod(home, which)
        code, edits = patch(src, which, block)
        meta = dict(meta)
        meta["title"] = f"{meta.get('title', which.title())} (logos)"
        out[name] = (code, meta, edits)
    return out


def build(config: Config, home: Path) -> list[str]:
    planned = plan(config, home)
    for name in planned:
        own_folder(home / "mods" / name, home)
    report = ["Built from Herdr's shipped mods (mods/spaces, mods/picker):"]
    for name, (code, meta, edits) in planned.items():
        folder = home / "mods" / name
        folder.mkdir(parents=True, exist_ok=True)
        (folder / MARKER).write_text("Made by playbook-herdr-space-logos. "
                                     "`space_logos.py undo` removes this folder.\n", encoding="utf-8")
        write_text(folder / "mod.json", json.dumps(meta, indent=2) + "\n")
        write_text(folder / "main.js", code)
        files = [f"main.js ({edits} edits)", "mod.json"]
        if name == config.spaces_mod:
            files += copy_logos(config, folder / "logos")
        report.append(f"  mods/{name}/  " + ", ".join(files))
    return report


def copy_logos(config: Config, target: Path) -> list[str]:
    wanted = sorted({e["logo"] for e in config.spaces.values() if "logo" in e})
    target.mkdir(exist_ok=True)
    for stale in target.iterdir():
        if stale.is_file() and stale.name not in wanted:
            stale.unlink()
    for logo in wanted:
        shutil.copyfile(config.logos / logo, target / logo)
    return [f"logos/{logo}" for logo in wanted]


def backup_once(path: Path) -> Path:
    """Keep the file as it was before this tool first changed it. A later run
    never overwrites that copy, so undo always goes back to the start."""
    backup = path.with_name(path.name + BACKUP)
    if not backup.exists():
        shutil.copy2(path, backup)
    return backup


@dataclass
class FileChange:
    """A change to one of your files, worked out before anything is written."""
    path: Path
    data: object | None  # the new content; None when there is nothing to write
    report: str


def read_json(path: Path, home: Path) -> object:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as err:
        raise Stop(f"{path.relative_to(home)} is not valid JSON: line {err.lineno}, column {err.colno}")


def layout_change(home: Path, layout: str, config: Config) -> FileChange:
    """Point the blocks of one of your layouts at the new mods."""
    if not LAYOUT_NAME.match(layout):
        raise Stop(f"--layout takes the name of a layout in layouts/, like logos, not a path: {layout!r}")
    if layout in SHIPPED_LAYOUTS:
        raise Stop(f"{layout} is one of Herdr's own layouts, which Herdr replaces on every "
                   f"start; clone it first: herdr-app do layout.clone "
                   f"'{{\"name\":\"{layout}\",\"as\":\"logos\"}}', then use --layout logos")
    path = home / "layouts" / f"{layout}.json"
    if not path.is_file():
        raise Stop(f"no layout at layouts/{layout}.json; clone one first (see PLAYBOOK.md)")
    data = read_json(path, home)
    swap = {"spaces": config.spaces_mod, "picker": config.picker_mod}
    changed = already = 0

    def walk(node: object) -> None:
        nonlocal changed, already
        if isinstance(node, dict):
            content = node.get("content")
            if isinstance(content, dict) and isinstance(content.get("mod"), str):
                if content["mod"] in swap:
                    content["mod"] = swap[content["mod"]]
                    changed += 1
                elif content["mod"] in swap.values():
                    already += 1
            for value in node.values():
                walk(value)
        elif isinstance(node, list):
            for value in node:
                walk(value)

    walk(data)
    rel = f"layouts/{layout}.json"
    if not changed:
        if already:
            return FileChange(path, None, f"Layout {rel}: already uses the logo mods")
        raise Stop(f"{rel} has no block with the spaces or picker mod")
    blocks = "1 block now uses" if changed == 1 else f"{changed} blocks now use"
    return FileChange(path, data, f"Layout {rel}: {blocks} the logo mods (backup: {rel}{BACKUP})")


def keys_change(home: Path, config: Config) -> FileChange:
    """Point every key that opens Herdr's picker at the new picker."""
    path = home / "keys.json"
    if not path.is_file():
        return FileChange(path, None, "Keys: no keys.json in the Herdr home, so the keys were left as they are")
    data = read_json(path, home)
    changed = already = 0
    for section in data.values() if isinstance(data, dict) else []:
        if not isinstance(section, dict):
            continue
        for key, action in section.items():
            if action == "mod.open:picker":
                section[key] = f"mod.open:{config.picker_mod}"
                changed += 1
            elif (isinstance(action, dict) and action.get("command") == "mod.open"
                  and isinstance(action.get("args"), dict) and action["args"].get("name") == "picker"):
                action["args"]["name"] = config.picker_mod
                changed += 1
            elif action == f"mod.open:{config.picker_mod}":
                already += 1
    if not changed and already:
        return FileChange(path, None, f"Keys keys.json: already open {config.picker_mod}")
    if not changed:
        return FileChange(path, None, "Keys: no key opens Herdr's picker, so keys.json was left as it is")
    keys = "1 key now opens" if changed == 1 else f"{changed} keys now open"
    return FileChange(path, data, f"Keys keys.json: {keys} {config.picker_mod} (backup: keys.json{BACKUP})")


def apply(change: FileChange) -> str:
    if change.data is not None:
        backup_once(change.path)
        write_text(change.path, json.dumps(change.data, indent=2, ensure_ascii=False) + "\n")
    return change.report


def use_in_layout(home: Path, layout: str, config: Config) -> str:
    return apply(layout_change(home, layout, config))


def use_in_keys(home: Path, config: Config) -> str:
    return apply(keys_change(home, config))


def install(config: Config, home: Path, layout: str | None, keys: bool) -> list[str]:
    # Work out every change first, so a wrong layout name or a broken file
    # stops the install before anything is written.
    changes = [layout_change(home, layout, config)] if layout else []
    if keys:
        changes.append(keys_change(home, config))
    report = build(config, home)  # the mods before the layout: a layout must never name a missing mod
    return report + [apply(change) for change in changes]


def undo(home: Path) -> list[str]:
    """Remove what install did in this Herdr home: restore every file from its
    backup first (so no layout names a missing mod), then remove the mods."""
    report = []
    for backup in sorted([*home.glob("layouts/*.json" + BACKUP), *home.glob("keys.json" + BACKUP)]):
        original = backup.with_name(backup.name[: -len(BACKUP)])
        os.replace(backup, original)
        report.append(f"  {original.relative_to(home)} restored from its backup")
    mods = home / "mods"
    for folder in sorted(mods.iterdir()) if mods.is_dir() else []:
        if (folder / MARKER).is_file():
            shutil.rmtree(folder)
            report.append(f"  mods/{folder.name} removed")
    return report or ["  nothing to undo: this tool left nothing in this Herdr home"]


# ---- what it looks like ------------------------------------------------------

def describe(config: Config) -> str:
    """A text preview of the sidebar tiles."""
    sep = f' (separator "{config.separator}")' if config.separator else ""
    width = max(len("any other space"), *(len(n) for n in config.spaces))
    lines = [f"Space tiles from {config.path.name}{sep}:", ""]
    for name, e in config.spaces.items():
        if "logo" in e:
            tile = f"logo {e['logo']}"
            if "bg" in e:
                tile += f" on {e['bg']}"
            if e.get("pad"):
                tile += f", {e['pad']} px margin"
        else:
            tile = f"letter {e.get('letter') or letter_for(name, config.separator)}"
            tile += f" on {e['color']}" if "color" in e else " on Herdr's color for it"
        lines.append(f"  {name.ljust(width)}  {tile}")
    rule = " after the separator" if config.separator else ""
    lines.append(f"  {'any other space'.ljust(width)}  letter: its first{rule}, on Herdr's color for it")
    return "\n".join(lines) + "\n"


def svg_el(parent: ET.Element | None, tag: str, **attrs: str) -> ET.Element:
    attrib = {k.rstrip("_").replace("_", "-"): str(v) for k, v in attrs.items()}
    if parent is None:
        return ET.Element(f"{{{SVG_NS}}}{tag}", attrib)
    return ET.SubElement(parent, f"{{{SVG_NS}}}{tag}", attrib)


def nested_logo(parent: ET.Element, file: Path, x: float, y: float, size: float) -> None:
    """Put a logo inside the preview: an SVG nested as is, a PNG as a data URI
    (an SVG shown on a web page may not load other files)."""
    if file.suffix.lower() == ".png":
        data = base64.b64encode(file.read_bytes()).decode()
        svg_el(parent, "image", x=x, y=y, width=size, height=size, href=f"data:image/png;base64,{data}")
        return
    logo = ET.fromstring(file.read_text(encoding="utf-8"))
    if "viewBox" not in logo.attrib:
        w, h = (re.sub(r"[^0-9.]", "", logo.get(k, "")) for k in ("width", "height"))
        if w and h:
            logo.set("viewBox", f"0 0 {w} {h}")
    for key, value in (("x", x), ("y", y), ("width", size), ("height", size)):
        logo.set(key, str(value))
    parent.append(logo)


def preview_svg(config: Config) -> str:
    """The sidebar as a picture, made from the config: for the README."""
    row, top, width = 32, 44, 280
    height = top + row * len(config.spaces) + 12
    root = svg_el(None, "svg", width=width, height=height, viewBox=f"0 0 {width} {height}")
    svg_el(root, "rect", width=width, height=height, rx=12, fill="#161a22")
    font = "Inter, Segoe UI, Helvetica, Arial, sans-serif"
    title = svg_el(root, "text", x=16, y=28, fill="#8b93a7", font_family=font, font_size=13)
